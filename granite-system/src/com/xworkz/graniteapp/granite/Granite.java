package com.xworkz.graniteapp.granite;

    public class Granite {
        private int graniteCode;
        private String graniteBrand;
        private String graniteType;
        private String color;
        private double price;
        private String graniteGrade;
        private int size;

        public void setGraniteCode(int graniteCode) {
            this.graniteCode = graniteCode;
        }
        public int getGraniteCode() {
            return graniteCode;
        }

        public void setGraniteBrand(String graniteBrand) {
            this.graniteBrand = graniteBrand;
        }
        public String getGraniteBrand() {
            return graniteBrand;
        }

        public void setGraniteType(String graniteType) {
            this.graniteType = graniteType;
        }
        public String getGraniteType() {
            return graniteType;
        }

        public void setColor(String color) {
            this.color = color;
        }
        public String getColor() {
            return color;
        }

        public void setPrice(double price) {
            this.price = price;
        }
        public double getPrice() {
            return price;
        }

        public void setGraniteGrade(String graniteGrade) {
            this.graniteGrade = graniteGrade;
        }
        public String getGraniteGrade() {
            return graniteGrade;
        }

        public void setSize(int size) {
            this.size = size;
        }
        public int getSize() {
            return size;
        }
    }


